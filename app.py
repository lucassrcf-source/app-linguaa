@app.get("/captions/list")
def captions_list():
    video_id = (request.args.get("videoId") or "").strip()
    if not video_id:
        return jsonify({"error": "videoId obrigatório"}), 400
    try:
        tracks = _list_tracks(video_id)
        return jsonify({"videoId": video_id, "tracks": tracks, "engine": "yt-dlp"})
    except Exception as e:
        return jsonify({"error": str(e), "tracks": []}), 500


@app.get("/captions")
def captions():
    video_id = (request.args.get("videoId") or "").strip()
    lang = (request.args.get("lang") or "en").strip()
    force = request.args.get("force", "0") == "1"

    if not video_id:
        return jsonify({"error": "videoId obrigatório"}), 400

    if not force:
        cached = _load_cache(video_id, lang)
        if cached:
            cached["cached"] = True
            return jsonify(cached)

    t0 = time.time()
    try:
        vtt, lang_used, is_auto = _download_vtt(video_id, lang)
        cues = _parse_vtt(vtt)
        if not cues:
            raise RuntimeError("VTT vazio após parse")
    except Exception as e:
        return jsonify({"error": f"Falha ao baixar legenda: {e}"}), 502

    srt = _cues_to_srt(cues)
    payload = {
        "videoId": video_id,
        "lang": lang_used,
        "requestedLang": lang,
        "isAutoGenerated": is_auto,
        "cached": False,
        "ms": int((time.time() - t0) * 1000),
        "engine": "yt-dlp",
        "cues": cues,
        "srt": srt,
        "count": len(cues),
    }
    _save_cache(video_id, lang, payload)
    if lang_used != lang:
        _save_cache(video_id, lang_used, payload)
    return jsonify(payload)


