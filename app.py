@app.get("/search")
def search():
    """
    Busca vídeos no YouTube via yt-dlp (sem API key do Google).
    q=termo  lang=en|es|pt  limit=12
    """
    q = (request.args.get("q") or "").strip()
    lang = (request.args.get("lang") or "en").strip().lower()
    try:
        limit = max(1, min(20, int(request.args.get("limit") or "12")))
    except ValueError:
        limit = 12

    if not q:
        return jsonify({"error": "q (busca) obrigatório", "results": []}), 400

    # Viés de idioma na query (yt-dlp não tem filtro oficial de idioma)
    bias = {
        "en": "english",
        "es": "español spanish",
        "pt": "português portuguese",
    }.get(lang, "")
    full_q = f"{q} {bias}".strip() if bias else q

    try:
        opts = {
            "quiet": True,
            "no_warnings": True,
            "extract_flat": True,
            "skip_download": True,
        }
        with yt_dlp.YoutubeDL(opts) as ydl:
            info = ydl.extract_info(f"ytsearch{limit}:{full_q}", download=False)

        entries = info.get("entries") or []
        results = []
        for e in entries:
            if not e:
                continue
            vid = e.get("id") or e.get("url") or ""
            if not vid or len(str(vid)) < 6:
                continue
            # extract_flat às vezes devolve URL completa
            if "watch?v=" in str(vid):
                m = re.search(r"v=([\w-]{11})", str(vid))
                vid = m.group(1) if m else vid
            thumb = None
            thumbs = e.get("thumbnails") or []
            if thumbs:
                thumb = thumbs[-1].get("url")
            thumb = thumb or e.get("thumbnail")
            if not thumb and len(str(vid)) == 11:
                thumb = f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg"
            duration = e.get("duration")
            results.append(
                {
                    "id": str(vid)[:11] if len(str(vid)) >= 11 else str(vid),
                    "title": e.get("title") or str(vid),
                    "author": e.get("uploader")
                    or e.get("channel")
                    or e.get("uploader_id")
                    or "",
                    "thumbnailUrl": thumb,
                    "durationMs": int(duration * 1000) if duration else None,
                }
            )

        return jsonify(
            {
                "q": q,
                "lang": lang,
                "count": len(results),
                "results": results,
                "engine": "yt-dlp",
            }
        )
    except Exception as e:
        return jsonify({"error": str(e), "results": []}), 502


